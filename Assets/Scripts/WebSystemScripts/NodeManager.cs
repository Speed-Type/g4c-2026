using UnityEngine;
using System;

public class NodeManager : MonoBehaviour
{
    //Variables in Inspector
    public RoguelikeGameplayController rgController;
    [SerializeField] private GameObject UIParentGO;
    [SerializeField] private GameObject playerMarkerGO;
    [SerializeField] private GameObject threadGO;
    [SerializeField] private Node currentNode;

    [Header("Web Generation Parameters")]
    [Tooltip("Number of Web Radii must be >= 3")]
    [SerializeField] private int webNumRadii;
    [SerializeField] private int webNumCircleWebs;
    [Tooltip("The radii for each individual circle; length of array must be equal to numCircleWebs")]
    [SerializeField] private float[] webRadiusSize;
    [SerializeField] private GameObject[] nodeTypes;
    [SerializeField] private float[] nodeWeights;
    [Tooltip("An array of max distances generated by random function; lengthof array must be equal to numCircleWebs")]
    [SerializeField] private float[] nodePositionRandomization;

    [Header("Web Animations Timing")]
    public static float playerTravelAnimTime = 1f;

    public void GenerateWeb()
    {
        //Set Node's NodeManager
        Node.SetNodeManager(this);

        //Generate the node types
        GameObject[] generatedNodeTypes = GenerateRandomNodes();

        //Create center
        GameObject centerNodeGO = Instantiate(generatedNodeTypes[0], UIParentGO.transform);
        Node centerNode = centerNodeGO.GetComponent<Node>();
        centerNode.GetComponent<RectTransform>().localPosition = Vector3.zero;
        centerNodeGO.name += "@Center"; //rename

        //Setup array for circling node generation logic
        Node[] previousCircle = new Node[webNumRadii];
        for(int i = 0; i < webNumRadii; i++)
        {
            previousCircle[i] = centerNode;
        }

        //Create circles
        float currentRadius = 0;
        for(int i = 0; i < webNumCircleWebs; i++)
        {
            currentRadius += webRadiusSize[i];
            for(int j = 0; j < webNumRadii; j++)
            {
                //Create new node
                GameObject newNodeGO = Instantiate(generatedNodeTypes[i * webNumRadii + j], UIParentGO.transform);
                Node newNode = newNodeGO.GetComponent<Node>();
                newNodeGO.name += "@Radius " + j + ", Circle " + i; //rename

                //Connect pointers, add to list
                newNode.AddNode(previousCircle[j]);
                previousCircle[j].AddNode(newNode);

                //Save data before replacing nodes in the array
                RectTransform previousNodeRectTransform = previousCircle[j].gameObject.GetComponent<RectTransform>();
                RectTransform newNodeRectTransform = newNodeGO.GetComponent<RectTransform>();

                //Replace previous node in the list with the new node
                previousCircle[j] = newNode;

                //Reposition the new node graphically
                Vector3 newPosition = new Vector3(UnityEngine.Random.Range(nodePositionRandomization[i] * -1, nodePositionRandomization[i]) + currentRadius * (float)Math.Cos(2 * Math.PI * ((float)j / webNumRadii)), UnityEngine.Random.Range(nodePositionRandomization[i] * -1, nodePositionRandomization[i]) + currentRadius * (float)Math.Sin(2 * Math.PI * ((float)j / webNumRadii)), 0);
                newNodeRectTransform.localPosition = newPosition;    

                //Add web thread between graphically
                AddThread(previousNodeRectTransform, newNodeRectTransform);

                //In the case that this is the start node, update currentNode
                if(generatedNodeTypes[i * webNumRadii + j] == nodeTypes[0]) //note that nodeTypes[0] is the start node
                {
                    currentNode = newNode;
                }
            }

            //Connect all the nodes in the previousCircle array
            for(int j = 0; j < webNumRadii - 1; j++)
            {
                previousCircle[j].AddNode(previousCircle[j+1]);
                previousCircle[j+1].AddNode(previousCircle[j]);
                AddThread(previousCircle[j].GetComponent<RectTransform>(), previousCircle[j+1].GetComponent<RectTransform>());
            }

            //Connect first and last nodes
            previousCircle[0].AddNode(previousCircle[previousCircle.Length - 1]);
            previousCircle[previousCircle.Length - 1].AddNode(previousCircle[0]);
            AddThread(previousCircle[0].GetComponent<RectTransform>(), previousCircle[previousCircle.Length - 1].GetComponent<RectTransform>());
        }

        //Put the player marker in the right place
        UpdatePlayerMarker();

        //Visit the current node
        currentNode.VisitNode();
    }
    
    private GameObject[] GenerateRandomNodes()
    {
        //Create array
        GameObject[] generatedNodeTypes = new GameObject[1 + webNumRadii * webNumCircleWebs];

        //Center node is guaranteed [TODO]
        generatedNodeTypes[0] = nodeTypes[2]; //temporarily, it's a scavenge node

        //Fill in rest randomly
        float totalRandomPool = 0;
        foreach(float f in nodeWeights)
        {
            totalRandomPool += f; //sum the total weights for each node
        }

        for(int i = 1; i < generatedNodeTypes.Length; i++)
        {
            //Generate random number from [0, totalWeights]
            float rand = UnityEngine.Random.Range(0f, totalRandomPool);
            float current = 0;

            for(int j = 0; j < nodeTypes.Length; j++)
            {
                current += nodeWeights[j];
                if(current >= rand)
                {
                    //This is the correct gameobject
                    generatedNodeTypes[i] = nodeTypes[j];
                    break;
                }
            }
        }

        //Select a starting node
        int randomNum = UnityEngine.Random.Range(1 + webNumRadii * (webNumCircleWebs - 1), generatedNodeTypes.Length - 1);
        generatedNodeTypes[randomNum] = nodeTypes[0];

        return generatedNodeTypes;
    }

    private void AddThread(RectTransform rectTransform1, RectTransform rectTransform2)
    {
        //Create new thread
        RectTransform threadRectTransform = Instantiate(threadGO, UIParentGO.transform).GetComponent<RectTransform>();
        threadRectTransform.SetAsFirstSibling();

        //Set thread center to midpoint
        threadRectTransform.localPosition = (rectTransform1.localPosition + rectTransform2.localPosition) / 2;
        
        //rotates thread as necessary
        Vector3 differenceVector = rectTransform2.localPosition - rectTransform1.localPosition;
        float angle = (float)Math.Atan2(differenceVector.y, differenceVector.x) * 180 / (float)Math.PI;
        threadRectTransform.localEulerAngles = new Vector3(0, 0, angle + 90);

        //scales thread as necessary
        threadRectTransform.sizeDelta *= new Vector2(1, (float)Math.Sqrt(Math.Pow(rectTransform2.localPosition.x - rectTransform1.localPosition.x, 2) + Math.Pow(rectTransform2.localPosition.y - rectTransform1.localPosition.y, 2)));
    }

    //Function to replace a node with another
    public void ReplaceNode(GameObject nodeToReplace, NodeTypes newNodeType)
    {
        //Instantiate the new node, move it to the right position
        GameObject newNodeGO = Instantiate(nodeTypes[(int)newNodeType], UIParentGO.transform);
        newNodeGO.GetComponent<RectTransform>().localPosition = nodeToReplace.GetComponent<RectTransform>().localPosition;
        newNodeGO.GetComponent<RectTransform>().SetSiblingIndex(newNodeGO.transform.parent.childCount - 2);

        //Set the pointer values in the new node to the pointer values of the old node
        foreach(Node node in nodeToReplace.GetComponent<Node>().GetNodeList())
        {
            newNodeGO.GetComponent<Node>().AddNode(node); //Sets this node's own pointers
            node.GetComponent<Node>().RemoveNode(nodeToReplace.GetComponent<Node>());
            node.GetComponent<Node>().AddNode(newNodeGO.GetComponent<Node>());
        }

        //If the node to replace is also the current node, update current node pointer
        if(nodeToReplace.GetComponent<Node>() == currentNode)
        {
            currentNode = newNodeGO.GetComponent<Node>();
        }

        //Delete the node to replace
        Destroy(nodeToReplace);
    }

    //Function to check if this node is reachable from the current node; note that the first node is auto allowed
    private bool isFirstNode = true;
    public bool TryVisitNode(Node nodeToVisit)
    {
        if(isFirstNode || currentNode.HasNode(nodeToVisit))
        {
            isFirstNode = false;

            //Now, clean up all fragments
            Fragment.FilterFragments();

            //Reset player bites
            RoguelikeGameplayController.ResetBites();

            //*******HERE, check if the previous node was anything that needs to be replaced upon exit
            if(currentNode.nodeType == NodeTypes.Scavenge)
            {
                ReplaceNode(currentNode.gameObject, NodeTypes.Empty);
            }

            currentNode = nodeToVisit; //update the current node

            UpdatePlayerMarker();
            return true;
        }
        return false;
    }

    //Tween player token to the proper node
    private void UpdatePlayerMarker()
    {
        playerMarkerGO.transform.SetAsLastSibling();
        LeanTween.move(playerMarkerGO.GetComponent<RectTransform>(), currentNode.GetComponent<RectTransform>().localPosition, playerTravelAnimTime).setEase(LeanTweenType.easeInOutQuad);
    }

    void Start()
    {
        GenerateWeb();
    }
}

//NOTE: The values in this enum must line up with the order of entries in nodeTypes array
public enum NodeTypes
{
    Start,
    Empty,
    Scavenge
}