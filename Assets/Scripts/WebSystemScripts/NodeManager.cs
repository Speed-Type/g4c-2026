using UnityEngine;
using System;
using System.Collections.Generic;

public class NodeManager : MonoBehaviour
{
    //Variables in Inspector
    [Header("Node Map References")]
    [SerializeField] private GameObject UIParentGO;
    [SerializeField] private GameObject playerMarkerGO;
    [SerializeField] private GameObject spiderMarkerGO;
    [SerializeField] private GameObject threadGO;
    public Node playerNode;
    public Node spiderNode;

    [Header("Web Generation Parameters")]
    [Tooltip("Number of Web Radii must be >= 3")]
    [SerializeField] private int webNumRadii;
    [SerializeField] private int webNumCircleWebs;
    [Tooltip("The radii for each individual circle; length of array must be equal to numCircleWebs")]
    [SerializeField] private float[] webRadiusSize;
    [SerializeField] private GameObject[] nodeTypes;
    [SerializeField] private float[] nodeWeights;
    [Tooltip("An array of max distances generated by random function; lengthof array must be equal to numCircleWebs")]
    [SerializeField] private float[] nodePositionRandomization;

    [Header("Web Animations Timing")]
    [SerializeField] private float playerTravelAnimTime = .75f;
    [SerializeField] private float spiderTravelAnimTime = .5f;
    [SerializeField] private float spiderRotateAnimTime = .2f;
    [SerializeField] private float spiderAnticipationAnimTime = 2f;
    [SerializeField] private float spiderAnticipationAnimMaxStrength = 30f;
    [SerializeField] private float spiderAnticipationAnimMaxFrequency = 40f;
    [SerializeField] private float spiderAnticipationAnimPause = 1f;

    [Header("Particle Prefabs for Spider Pursue Indication")]
    [SerializeField] private GameObject spiderPursueParticle;
    [SerializeField] private GameObject spiderConfusedParticle;

    [Header("Caterpillar Movement Reference Transforms")]
    [SerializeField] private GameObject caterpillarGO;
    private GameObject enemyBugGO;
    [SerializeField] private Transform idleCaterpillarPositionTransform;
    [SerializeField] private Transform scavengeCaterpillarPositionTransform;
    [SerializeField] private Transform scavengeEnemyPositionTransform;
    [SerializeField] private Transform combatEnemyPositionTransform;

    public static NodeManager instance;
    public static bool isMovingNodes = false;
    public static bool overrideVisitConditions = false;

    void Awake()
    {
        instance = this;
    }

    void Start()
    {
        GenerateWeb();

        isMovingNodes = false;
    }

    public void GenerateWeb()
    {
        //Set Node's NodeManager
        Node.SetNodeManager(this);

        //Generate the node types
        GameObject[] generatedNodeTypes = GenerateRandomNodes();

        //Create center
        GameObject centerNodeGO = Instantiate(generatedNodeTypes[0], UIParentGO.transform);
        Node centerNode = centerNodeGO.GetComponent<Node>();
        centerNode.GetComponent<RectTransform>().localPosition = Vector3.zero;
        centerNodeGO.name += "@Center"; //rename

        //Set spider position at center
        spiderNode = centerNode;

        //Upgrade center
        centerNode.UpgradeLoot();

        //Setup array for circling node generation logic
        Node[] previousCircle = new Node[webNumRadii];
        for(int i = 0; i < webNumRadii; i++)
        {
            previousCircle[i] = centerNode;
        }

        //Create circles
        float currentRadius = 0;
        for(int i = 0; i < webNumCircleWebs; i++)
        {
            currentRadius += webRadiusSize[i];
            for(int j = 0; j < webNumRadii; j++)
            {
                //Create new node
                GameObject newNodeGO = Instantiate(generatedNodeTypes[i * webNumRadii + j], UIParentGO.transform);
                Node newNode = newNodeGO.GetComponent<Node>();
                newNodeGO.name += "@Radius " + j + ", Circle " + i; //rename

                //Connect pointers, add to list
                newNode.AddNode(previousCircle[j]);
                previousCircle[j].AddNode(newNode);

                //Save data before replacing nodes in the array
                RectTransform previousNodeRectTransform = previousCircle[j].gameObject.GetComponent<RectTransform>();
                RectTransform newNodeRectTransform = newNodeGO.GetComponent<RectTransform>();

                //Replace previous node in the list with the new node
                previousCircle[j] = newNode;

                //Reposition the new node graphically
                Vector3 newPosition = new Vector3(UnityEngine.Random.Range(nodePositionRandomization[i] * -1, nodePositionRandomization[i]) + currentRadius * (float)Math.Cos(2 * Math.PI * ((float)j / webNumRadii)), UnityEngine.Random.Range(nodePositionRandomization[i] * -1, nodePositionRandomization[i]) + currentRadius * (float)Math.Sin(2 * Math.PI * ((float)j / webNumRadii)), 0);
                newNodeRectTransform.localPosition = newPosition;    

                //Add web thread between graphically
                AddThread(previousNodeRectTransform, newNodeRectTransform);

                //In the case that this is the start node, update playerNode
                if(generatedNodeTypes[i * webNumRadii + j] == nodeTypes[0]) //note that nodeTypes[0] is the start node
                {
                    playerNode = newNode;
                }
            }

            //Connect all the nodes in the previousCircle array
            for(int j = 0; j < webNumRadii - 1; j++)
            {
                previousCircle[j].AddNode(previousCircle[j+1]);
                previousCircle[j+1].AddNode(previousCircle[j]);
                AddThread(previousCircle[j].GetComponent<RectTransform>(), previousCircle[j+1].GetComponent<RectTransform>());
            }

            //Connect first and last nodes
            previousCircle[0].AddNode(previousCircle[previousCircle.Length - 1]);
            previousCircle[previousCircle.Length - 1].AddNode(previousCircle[0]);
            AddThread(previousCircle[0].GetComponent<RectTransform>(), previousCircle[previousCircle.Length - 1].GetComponent<RectTransform>());
        }

        //Visit the current node
        playerNode.VisitNode();
    }
    
    private GameObject[] GenerateRandomNodes()
    {
        //Create array
        GameObject[] generatedNodeTypes = new GameObject[1 + webNumRadii * webNumCircleWebs];

        //Center node is guaranteed a scavenger node
        generatedNodeTypes[0] = nodeTypes[2];

        //Fill in rest randomly
        float totalRandomPool = 0;
        foreach(float f in nodeWeights)
        {
            totalRandomPool += f; //sum the total weights for each node
        }

        for(int i = 1; i < generatedNodeTypes.Length; i++)
        {
            //Generate random number from [0, totalWeights]
            float rand = UnityEngine.Random.Range(0f, totalRandomPool);
            float current = 0;

            for(int j = 0; j < nodeTypes.Length; j++)
            {
                current += nodeWeights[j];
                if(current >= rand)
                {
                    //This is the correct gameobject
                    generatedNodeTypes[i] = nodeTypes[j];
                    break;
                }
            }
        }

        //Select a starting node
        int randomNum = UnityEngine.Random.Range(1 + webNumRadii * (webNumCircleWebs - 1), generatedNodeTypes.Length - 1);
        generatedNodeTypes[randomNum] = nodeTypes[0];

        return generatedNodeTypes;
    }

    private void AddThread(RectTransform rectTransform1, RectTransform rectTransform2)
    {
        //Create new thread
        RectTransform threadRectTransform = Instantiate(threadGO, UIParentGO.transform).GetComponent<RectTransform>();
        threadRectTransform.SetAsFirstSibling();

        //Set thread center to midpoint
        threadRectTransform.localPosition = (rectTransform1.localPosition + rectTransform2.localPosition) / 2;
        
        //rotates thread as necessary
        Vector3 differenceVector = rectTransform2.localPosition - rectTransform1.localPosition;
        float angle = (float)Math.Atan2(differenceVector.y, differenceVector.x) * 180 / (float)Math.PI;
        threadRectTransform.localEulerAngles = new Vector3(0, 0, angle + 90);

        //scales thread as necessary
        threadRectTransform.sizeDelta *= new Vector2(1, (float)Math.Sqrt(Math.Pow(rectTransform2.localPosition.x - rectTransform1.localPosition.x, 2) + Math.Pow(rectTransform2.localPosition.y - rectTransform1.localPosition.y, 2)));
    }

    //Function to replace a node with another
    public void ReplaceNode(GameObject nodeToReplace, NodeTypes newNodeType, bool setVisited = false)
    {
        //Instantiate the new node, move it to the right position
        GameObject newNodeGO = Instantiate(nodeTypes[(int)newNodeType], UIParentGO.transform);
        newNodeGO.GetComponent<RectTransform>().localPosition = nodeToReplace.GetComponent<RectTransform>().localPosition;
        newNodeGO.GetComponent<RectTransform>().SetSiblingIndex(newNodeGO.transform.parent.childCount - 2);

        //Set the pointer values in the new node to the pointer values of the old node
        foreach(Node node in nodeToReplace.GetComponent<Node>().GetNodeList())
        {
            newNodeGO.GetComponent<Node>().AddNode(node); //Sets this node's own pointers
            node.GetComponent<Node>().RemoveNode(nodeToReplace.GetComponent<Node>());
            node.GetComponent<Node>().AddNode(newNodeGO.GetComponent<Node>());
        }

        //If the node to replace is also the current node, update current node pointer
        if(nodeToReplace.GetComponent<Node>() == playerNode)
        {
            playerNode = newNodeGO.GetComponent<Node>();
        }

        //Delete the node to replace
        Destroy(nodeToReplace);

        //If setVisited is true, we want to set this new node to be already visited
        if(setVisited) newNodeGO.GetComponent<Node>().SetNodeBGColorVisited();
    }

    //Function to check if this node is reachable from the current node; note that the first node is auto allowed
    private bool isFirstNode = true;
    public bool TryVisitNode(Node nodeToVisit)
    {
        if(overrideVisitConditions)
        {
            overrideVisitConditions = false; //Reset override

            //Activate node real quick
            UIParentGO.SetActive(true);
            UIParentGO.SetActive(false);

            SetBugModelsPosition(); //Set proper 3d bug models in scene
            playerMarkerGO.transform.SetAsLastSibling(); //Make sure player icon stays on top

            //Skip spider turn and go straight to node effects
            nodeToVisit.DoNodeEffects();

            return true;
        }
        else if(isFirstNode || playerNode.HasNode(nodeToVisit))
        {
            if(isMovingNodes) return false; //If already mid-node move, set it so that a node can't be selected
            isMovingNodes = true;

            isFirstNode = false;

            //Now, clean up all fragments
            Fragment.FilterFragments();

            //Reset player bites
            RoguelikeGameplayController.ResetBites();

            //Increase spider alertness
            RoguelikeGameplayController.instance.currentSpiderAlertness += 2;

            //Preload the hide method
            RoguelikeGameplayController.instance.HideMapPreloadFromScript();

            //*******HERE, check if the previous node was anything that needs to be replaced upon exit*****
            
            //Replace scavenge nodes with empty nodes
            if(playerNode.nodeType == NodeTypes.Scavenge)
            {
                ReplaceNode(playerNode.gameObject, NodeTypes.Empty, true);
            }

            //*********************************************************************************************

            playerNode = nodeToVisit; //update the current node

            RevealAdjacentNodes(); //Show adjacent nodes as necessary

            UpdatePlayerMarker(); //Make player marker actually move to the selected node

            SetBugModelsPosition(); //Update 3d bug models for this new node

            return true;
        }
        return false;
    }

    //Method that reveals the proper number of surrounding nodes of the player, according to their upgrades
    private void RevealAdjacentNodes()
    {
        for(int i = 0; i < RoguelikeGameplayController.instance.emptyNodesToReveal; i++)
        {
            if(TryRevealNode(playerNode, NodeTypes.Empty) == false) break;
        }

        for(int i = 0; i < RoguelikeGameplayController.instance.scavengerNodesToReveal; i++)
        {
            if(TryRevealNode(playerNode, NodeTypes.Scavenge) == false) break;
        }

        for(int i = 0; i < RoguelikeGameplayController.instance.combatNodesToReveal; i++)
        {
            if(TryRevealNode(playerNode, NodeTypes.Combat) == false) break;
        }
    }

    //Method to try to reveal a single not-yet-revealed node of a given type that is adjacent to the parameter node
    //Returns: Whether or not it was successful
    private bool TryRevealNode(Node nodeToCheck, NodeTypes nodeType, bool doRecursion = true)
    {
        //Store data to reduce number of accesses
        List<Node> adjacentNodes = nodeToCheck.GetNodeList();
        int totalNodes = adjacentNodes.Count;

        //Pick a random node to check first
        int firstIndex = UnityEngine.Random.Range(0, totalNodes);

        //Looping around from that node, check nodes to see if they match the nodeType parameter
        for(int i = 0; i < totalNodes; i++)
        {
            Node checkingNode = adjacentNodes[(firstIndex + i) % totalNodes];

            //Skip any "adjacent" nodes that are really just the node the player is already going to
            if(checkingNode == playerNode) continue;

            //Check if this node itself hits all conditions
            if(checkingNode.nodeType == nodeType && !checkingNode.isRevealed)
            {
                checkingNode.RevealNode();
                return true;
            }

            //Otherwise, if this is not already a recursive call, check if this node's adjacent nodes hit conditions
            if(doRecursion && TryRevealNode(checkingNode, nodeType, false))
            {
                return true;
            }
        }

        //If nothing else, return false
        return false;
    }

    //Tween player token to the proper node
    private void UpdatePlayerMarker()
    {
        playerMarkerGO.transform.SetAsLastSibling();
        LeanTween.move(playerMarkerGO.GetComponent<RectTransform>(), playerNode.GetComponent<RectTransform>().localPosition, playerTravelAnimTime)
            .setEase(LeanTweenType.easeInOutSine)
            .setOnComplete(() =>
            {
                //Begin spider movement
                DoSpiderTurn();
            });
    }

    //Method that handles the spider's turn
    private bool hasAttackedPlayer = false;
    private Node lastSpiderNode;
    private void DoSpiderTurn(int currentMoveNum = 0)
    {
        spiderMarkerGO.transform.SetAsLastSibling();
        if(spiderNode == playerNode && !hasAttackedPlayer) //CASE 1: SPIDER AND PLAYER ON SAME NODE
        {
            hasAttackedPlayer = true;

            //Do shaking effect for anticipation
            RectTransform spiderRect = spiderMarkerGO.GetComponent<RectTransform>();
            Vector2 originalPos = spiderRect.anchoredPosition;
            float time = 0f;

            LeanTween.value(spiderMarkerGO, 0f, 1f, spiderAnticipationAnimTime)
            .setOnUpdate((float t) =>
            {
                //t is the parameter that goes from 0 to 1 over duration

                //Strength increases over time
                float strength = Mathf.Lerp(0f, spiderAnticipationAnimMaxStrength, t);

                //Frequency increases over time
                float frequency = Mathf.Lerp(5f, spiderAnticipationAnimMaxFrequency, t);

                time += Time.deltaTime * frequency;

                Vector2 offset = new Vector2(
                    Mathf.PerlinNoise(time, 0f) - 0.5f,
                    Mathf.PerlinNoise(0f, time) - 0.5f
                ) * strength;

                spiderRect.anchoredPosition = originalPos + offset;

                //Screenshake
                ScreenShake.instance.SetTrauma(t / 10f); //So, 0 to .10f intensity
            })
            .setOnComplete(() =>
            {
                spiderRect.anchoredPosition = originalPos;

                LeanTween.delayedCall(spiderAnticipationAnimPause, () =>
                {
                    //Calculate if the player survives
                    if(RoguelikeGameplayController.instance.CheckCaterpillarSurvives())
                    {
                        Debug.Log("SAFE");
                        //Player lives, spider moves on (and moves off of player node)
                        //We give the spider an extra turn (by not incrementing currentMoveNum)
                        //This way the spider gets to move one more square, and it stops moving afterwards because hasAttackedPlayer == true
                        DoSpiderTurn(currentMoveNum - 1);
                    }
                    else
                    {
                        //GAME OVER
                        Debug.Log("GAME OVER");
                    }
                });
            });
        }
        else if(currentMoveNum == RoguelikeGameplayController.instance.spiderMovesPerTurn) //CASE 2: SPIDER HAS NO MORE MOVES
        {
            //Call to hide map
            RoguelikeGameplayController.instance.HideMap(true);

            //Call method for playerNode to its their thing
            playerNode.DoNodeEffects();

            //Set player attackable again
            hasAttackedPlayer = false;
        }
        else //CASE 3: SPIDER JUST MOVES A NODE
        {
            Node previousNode = spiderNode; //Save the previous node to set it later

            //Calculate which node spider should move to
            if(UnityEngine.Random.Range(0f,1f) > RoguelikeGameplayController.ChanceForSpiderToPursue()) //Just a random node
            {
                Node newNode;
                do
                {
                    newNode = spiderNode.GetNodeList()[UnityEngine.Random.Range(0, spiderNode.GetNodeList().Count)];
                }
                while(newNode == lastSpiderNode);

                spiderNode = newNode;
            }
            else //A node specifically toward the player
            {
                //Screenshake
                ScreenShake.instance.AddTrauma(0.10f);
                
                List<Node> neighborNodes = spiderNode.GetNodeList();
                Node bestNode = neighborNodes[0];
                float bestDistance = float.MaxValue;

                //Algorithm literally just finds the smallest screen distance between two nodes
                foreach(Node n in neighborNodes)
                {
                    if(n == lastSpiderNode) continue; //Avoid backtracking to the most directly previous node

                    float dist = Vector2.Distance(
                        n.GetComponent<RectTransform>().localPosition,
                        playerNode.GetComponent<RectTransform>().localPosition
                    );

                    if(dist < bestDistance)
                    {
                        bestDistance = dist;
                        bestNode = n;
                    }
                }

                spiderNode = bestNode; //Set the node to the closest node

                //Spawn particles to indicate spider pursuing
                if(!hasAttackedPlayer) RoguelikeCameraController.SpawnParticle(spiderMarkerGO.transform.position, spiderPursueParticle);
            }
            
            lastSpiderNode = previousNode; //Update the previous node for the next call

            //Spawn particles for safe if this is the safe movement
            if(hasAttackedPlayer) RoguelikeCameraController.SpawnParticle(spiderMarkerGO.transform.position, spiderConfusedParticle);

            //Do the math to calculate new rotation
            RectTransform spiderRect = spiderMarkerGO.GetComponent<RectTransform>();
            RectTransform targetRect = spiderNode.GetComponent<RectTransform>();
            Vector2 dir = targetRect.localPosition - spiderRect.localPosition;
            float angle = Mathf.Atan2(dir.y, dir.x) * Mathf.Rad2Deg + 90f;

            //Tween spider's rotation to face the new spiderNode's RectTransform
            LeanTween.rotateZ(spiderMarkerGO, angle, spiderRotateAnimTime)
            .setEaseInOutSine()
            .setOnComplete(() =>
            {
                //Screenshake
                ScreenShake.instance.AddTrauma(0.06f);

                //Actually move spider
                LeanTween.move(spiderMarkerGO.GetComponent<RectTransform>(), spiderNode.GetComponent<RectTransform>().localPosition, spiderTravelAnimTime)
                .setEaseOutExpo()
                .setOnComplete(() =>
                {
                    if(!hasAttackedPlayer)
                    {
                        DoSpiderTurn(currentMoveNum + 1); //Keep moving only if the spider has not just attacked
                    }
                    else //IN THIS CASE, SPIDER HAS JUST MOVED AWAY FROM PLAYER
                    {
                        //Call to hide map
                        RoguelikeGameplayController.instance.HideMap(true);

                        //Call method for playerNode to its their thing
                        playerNode.DoNodeEffects();

                        //Set player attackable again
                        hasAttackedPlayer = false;
                    }
                });
            });
        }
    }

    //Spawn/move 3d bugs in proper spots
    private void SetBugModelsPosition()
    {
        //Delete previous enemy bug if there is one
        if(enemyBugGO != null) Destroy(enemyBugGO);

        //Determine caterpillar's position based on current node's type
        if(playerNode.nodeType == NodeTypes.Scavenge || playerNode.nodeType == NodeTypes.Combat)
        {
            caterpillarGO.transform.position = scavengeCaterpillarPositionTransform.position;

            //Then spawn the right bug
            if(playerNode.nodeType == NodeTypes.Scavenge)
            {
                //Enemy should be in scavenge position with randomized rotation
                enemyBugGO = Instantiate(playerNode.GetBugModel(), scavengeEnemyPositionTransform.position, Quaternion.Euler(0, UnityEngine.Random.Range(0,360), 0), scavengeEnemyPositionTransform);
            }
            else
            {
                enemyBugGO = Instantiate(playerNode.GetBugModel(), combatEnemyPositionTransform.position, combatEnemyPositionTransform.rotation, combatEnemyPositionTransform);
            }
        }
        else
        {
            caterpillarGO.transform.position = idleCaterpillarPositionTransform.position;
        }
    }

    //Method to hide the enemy bug, called from RGController when switching to inventory view
    public void HideEnemyBug()
    {
        if(enemyBugGO != null)
        {
            enemyBugGO.SetActive(false);
        }
    }

    //Method to show the enemy bug, called from RGController when switching back from inventory view
    public void ShowEnemyBug()
    {
        if(enemyBugGO != null)
        {
            enemyBugGO.SetActive(true);
        }
    }
}

//NOTE: The values in this enum must line up with the order of entries in nodeTypes array
public enum NodeTypes
{
    Start,
    Empty,
    Scavenge,
    Combat
}